def region_for(name: str) -> str:
    """按 name 前 1-3 字匹配 REGION_MAP; 默认 '其他'"""
    # 特殊: "外站保障手册——新加坡" 这类带前缀的, 先去掉前缀
    cleaned = name
    if "——" in cleaned:
        cleaned = cleaned.split("——", 1)[1]
    for k, v in REGION_MAP.items():
        if cleaned.startswith(k):
            return v
    return "其他"


def airport_for(name: str, status: str) -> str:
    """airport 显示名: name + '机场'; '（暂停）' 后缀保留"""
    base = name
    if "（暂停）" in base:
        base = base.replace("（暂停）", "")
    if "（待开航）" in base:
        base = base.replace("（待开航）", "")
    if "（国际）" in base:
        base = base.replace("（国际）", "")
    if "外站保障手册——" in base:
        base = base.replace("外站保障手册——", "")
    if "国际机场" in base or "国际机场" in name:
        return f"{base}"
    return f"{base}机场"


def parse_code(code: str):
    """'B-北京大兴' → ('B', '北京大兴')
    '外站保障手册——新加坡' → ('X', '外站保障手册——新加坡')
    '（待开航）A-阿拉木图' → ('A', '阿拉木图 (待开航)')
    """
    # 特殊: 带 '（待开航）' 前缀
    pending = False
    if "（待开航）" in code:
        pending = True
        code = code.replace("（待开航）", "").strip()

    if "-" in code:
        prefix, name = code.split("-", 1)
    else:
        prefix, name = "X", code

    if pending:
        name = f"{name} (待开航)"

    return prefix, name


